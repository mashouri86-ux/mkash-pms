export const dictionaries: Record<Lang, Dict> = { en, ar };
export type Key = keyof Dict;

export interface I18n {
  lang: Lang;
  t: (k: Key | string) => string;
  /** Pick the Arabic or English value. */
  pick: (arText?: string | null, enText?: string | null) => string;
  num: (n: number, digits?: number) => string;
  money: (n: number) => string;
  date: (iso?: string | null) => string;
  setLang: (l: Lang) => void;
}

export function makeI18n(lang: Lang, setLang: (l: Lang) => void): I18n {
  const d = dictionaries[lang] as Record<string, string>;
  const locale = lang === "ar" ? "ar-QA-u-nu-latn" : "en-GB";
  return {
    lang,
    setLang,
    t: (k) => d[k] ?? k,
    pick: (a, e) => (lang === "ar" ? a || e || "" : e || a || ""),
    num: (n, digits = 0) => n.toLocaleString(locale, { maximumFractionDigits: digits, minimumFractionDigits: digits }),
    money: (n) =>
      n >= 1e6
        ? `${(n / 1e6).toLocaleString(locale, { maximumFractionDigits: 1 })}${lang === "ar" ? " مليون" : "M"}`
        : n.toLocaleString(locale, { maximumFractionDigits: 0 }),
    date: (iso) => (iso ? new Date(iso).toLocaleDateString(locale, { day: "2-digit", month: "short", year: "numeric" }) : "—"),
  };
}

export const I18nContext = createContext<I18n>(makeI18n("en", () => undefined));
export const useI18n = () => useContext(I18nContext);
